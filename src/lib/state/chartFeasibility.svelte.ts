import type { Component } from "svelte";

import { LazySurface } from "../../lib/state/lazySurface.svelte";
import { syntheticChartProposal } from "../../features/charts/chartSamples";
import type { ChartSampleKind } from "../../features/charts/chartSamples";
import { ChartSurfaceState } from "../../features/charts/chartSurfaceState.svelte";
import type { ChartProposal } from "../../features/charts/chartSnapshot";

/** Identity shown beside the synthetic chart. */
export const CHART_TARGET_LABEL = "Synthetic metric series (offline, no cluster)";

const CHART_SURFACE_FAILURE = "The offline chart component could not be loaded. Try again.";

/** Props the lazily loaded chart surface accepts. */
export interface ChartSurfaceProps {
  /** Synchronous replacement-proposal reader; the proposal is admitted immediately. */
  readSnapshot: () => ChartProposal;
  /** Revision that changes whenever a new proposal is made. */
  revision: number;
  /** Visible projection written by the chart attachment. */
  view: ChartSurfaceState;
  /** Visible target identity. */
  targetLabel: string;
  /** Proposes one synthetic replacement kind. */
  onSample: (kind: ChartSampleKind) => void;
  /** Closes the surface and returns focus to its opener. */
  onClose: () => void;
}

/** A lazily imported Svelte component with {@link ChartSurfaceProps}. */
export type ChartSurfaceComponent = Component<ChartSurfaceProps>;

async function loadChartSurface(): Promise<ChartSurfaceComponent> {
  const module = await import("../../features/charts/ChartSurface.svelte");
  return module.default;
}

/**
 * Owner state for the synthetic chart feasibility surface.
 *
 * Only the requested proposal kind and a small sequence number are retained; the
 * timestamp and value arrays are generated synchronously at admission and never
 * stored in reactive state. uPlot and its stylesheet live in the lazily imported
 * surface chunk, so opening Home imports neither library.
 */
export class ChartFeasibilityState {
  #kind = $state<ChartSampleKind>("sample");
  #sequence = $state(1);
  /** Snapshot revision; every proposal increments it exactly once. */
  revision = $state(0);

  /** Attachment projection rendered beside the chart. */
  readonly view = new ChartSurfaceState();

  /** Lazily imported chart surface with generation-based cancellation. */
  readonly surface = new LazySurface<ChartSurfaceComponent>({
    load: loadChartSurface,
    failureMessage: CHART_SURFACE_FAILURE,
  });

  /**
   * Builds the currently proposed synthetic chart snapshot.
   *
   * Oversized histories are generated only when this method is called, so the
   * owner never keeps a rejected or evicted array alive between renders.
   *
   * @returns A newly generated proposal; callers must admit it synchronously.
   */
  readSnapshot(): ChartProposal {
    return syntheticChartProposal(this.#kind, this.#sequence);
  }

  /**
   * Proposes one synthetic replacement.
   *
   * @param kind Proposal kind generated by the next admission.
   */
  propose(kind: ChartSampleKind): void {
    this.#kind = kind;
    this.revision += 1;
  }

  /** Proposes the next ordinary sample with an increasing time base. */
  nextSample(): void {
    this.#sequence += 1;
    this.propose("sample");
  }

  /** Starts the lazy chart import and resets the visible projection. */
  async open(): Promise<void> {
    this.view.reset();
    await this.surface.open();
  }

  /** Cancels a pending import or unmounts the loaded surface. */
  close(): void {
    this.surface.close();
    this.view.reset();
  }
}
