import type { Component } from "svelte";

import { LazySurface } from "../../lib/state/lazySurface.svelte";
import { syntheticTerminalText } from "../../features/terminal/terminalSamples";
import type { TerminalSampleKind } from "../../features/terminal/terminalSamples";
import { TerminalSurfaceState } from "../../features/terminal/terminalSurfaceState.svelte";

/** Identity shown beside the synthetic terminal. */
export const TERMINAL_TARGET_LABEL = "Synthetic container output (offline, no cluster)";

const TERMINAL_SURFACE_FAILURE = "The offline terminal component could not be loaded. Try again.";

/** Props the lazily loaded terminal surface accepts. */
export interface TerminalSurfaceProps {
  /** Synchronous replacement-snapshot reader; the proposal is consumed at admission. */
  readSnapshot: () => string;
  /** Revision that changes whenever a new snapshot is proposed. */
  revision: number;
  /** Visible state written by the terminal attachment. */
  view: TerminalSurfaceState;
  /** Visible target identity. */
  targetLabel: string;
  /** Proposes one synthetic replacement kind. */
  onSample: (kind: TerminalSampleKind) => void;
  /** Closes the surface and returns focus to its opener. */
  onClose: () => void;
}

/** A lazily imported Svelte component with {@link TerminalSurfaceProps}. */
export type TerminalSurfaceComponent = Component<TerminalSurfaceProps>;

async function loadTerminalSurface(): Promise<TerminalSurfaceComponent> {
  const module = await import("../../features/terminal/TerminalSurface.svelte");
  return module.default;
}

/**
 * Owner state for the synthetic terminal feasibility surface.
 *
 * Only the requested snapshot kind and a small sequence number are retained;
 * the text is generated synchronously by {@link TerminalFeasibilityState.readSnapshot}
 * when the attachment admits it, so an oversized proposal never sits in
 * reactive state or a component prop. xterm.js, its stylesheet, and the replay
 * session live in the lazily imported surface chunk.
 */
export class TerminalFeasibilityState {
  #kind = $state<TerminalSampleKind>("sample");
  #sequence = $state(1);
  /** Snapshot revision; every proposal increments it exactly once. */
  revision = $state(0);

  /** Attachment projection rendered beside the terminal. */
  readonly view = new TerminalSurfaceState();

  /** Lazily imported terminal surface with generation-based cancellation. */
  readonly surface = new LazySurface<TerminalSurfaceComponent>({
    load: loadTerminalSurface,
    failureMessage: TERMINAL_SURFACE_FAILURE,
  });

  /**
   * Builds the currently proposed synthetic snapshot.
   *
   * @returns A newly generated proposal; callers must admit it synchronously.
   */
  readSnapshot(): string {
    return syntheticTerminalText(this.#kind, this.#sequence);
  }

  /**
   * Proposes one synthetic replacement.
   *
   * @param kind Snapshot kind generated by the next admission.
   */
  propose(kind: TerminalSampleKind): void {
    this.#kind = kind;
    this.revision += 1;
  }

  /** Proposes the next ordinary sample with an increasing sequence number. */
  nextSample(): void {
    this.#sequence += 1;
    this.propose("sample");
  }

  /** Starts the lazy terminal import and resets the visible projection. */
  async open(): Promise<void> {
    this.view.reset();
    await this.surface.open();
  }

  /** Cancels a pending import or unmounts the loaded surface. */
  close(): void {
    this.surface.close();
    this.view.reset();
  }
}
